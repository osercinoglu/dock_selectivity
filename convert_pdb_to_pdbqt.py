def check_system_resources(log=None):
    """Report CPU/RAM and a conservative worker recommendation.

    Called from main(), never at import: it logs, and a module that emits log
    records on import is a module you cannot use as a library.
    """
    log = log if log is not None else LOG
    try:
        # Get CPU and memory info
        cpu_count = multiprocessing.cpu_count()

        # Try to get memory info if psutil is available
        try:
            import psutil
            memory_gb = psutil.virtual_memory().total / (1024**3)
            log.info(f"System resources: {cpu_count} CPU cores, {memory_gb:.1f} GB RAM")

            # Provide recommendations based on system resources
            if memory_gb < 4:
                recommended_workers = min(cpu_count, 2)
                log.warning(f"Low memory detected. Recommended workers: {recommended_workers}")
            elif memory_gb < 8:
                recommended_workers = min(cpu_count, 4)
                log.info(f"Moderate memory detected. Recommended workers: {recommended_workers}")
            else:
                recommended_workers = min(cpu_count, 8)
                log.info(f"Sufficient memory detected. Recommended workers: {recommended_workers}")

        except ImportError:
            log.info(f"System resources: {cpu_count} CPU cores (memory info unavailable)")
            recommended_workers = min(cpu_count, 4)

        return recommended_workers

    except Exception as e:
        log.warning(f"Could not check system resources: {e}")
        return 2  # Conservative fallback


