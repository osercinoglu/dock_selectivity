def get_file_hash(file_path):
    """Calculate MD5 hash of a file to check for duplicates."""
    hash_md5 = hashlib.md5()
    with open(file_path, "rb") as f:
        for chunk in iter(lambda: f.read(4096), b""):
            hash_md5.update(chunk)
    return hash_md5.hexdigest()

def pdb_to_pdbqt_safe(pdb_path, pdbqt_path, pH=7.4):
    """
    Thread-safe wrapper for PDB to PDBQT conversion.
    
    Parameters
    ----------
    pdb_path: str or pathlib.Path
        Path to input PDB file.
    pdbqt_path: str or pathlib.Path
        Path to output PDBQT file.
    pH: float
        Protonation at given pH.
        
    Returns
    -------
    tuple: (success: bool, error_message: str or None)
    """
    try:
        # Import pybel in the function to avoid thread safety issues
        from openbabel import pybel
        
        # Read the PDB file
        molecules = list(pybel.readfile("pdb", str(pdb_path)))
        if not molecules:
            return False, "No molecules found in PDB file"
        
        molecule = molecules[0]
        
        # Add hydrogens and partial charges
        # Note: Commenting out pH correction as it might cause issues
        # molecule.OBMol.CorrectForPH(pH)
        # molecule.addh()
        
        # Add partial charges to each atom
        for atom in molecule.atoms:
            atom.OBAtom.GetPartialCharge()
        
        # Write PDBQT file
        molecule.write("pdbqt", str(pdbqt_path), overwrite=True)
        return True, None
        
    except Exception as e:
        return False, str(e)

def pdb_to_pdbqt(pdb_path, pdbqt_path, pH=7.4):
    """
    Convert a PDB file to a PDBQT file needed by docking programs of the AutoDock family.
    
    Parameters
    ----------
    pdb_path: str or pathlib.Path
        Path to input PDB file.
    pdbqt_path: str or pathlib.Path
        Path to output PDBQT file.
    pH: float
        Protonation at given pH.
        
    Returns
    -------
    bool: True if conversion successful, False otherwise
    """
    try:
        success, error = pdb_to_pdbqt_safe(pdb_path, pdbqt_path, pH)
        if not success:
            LOG.error(f"Error converting {pdb_path} to PDBQT: {error}")
        return success
    except Exception as e:
        LOG.error(f"Error converting {pdb_path} to PDBQT: {e}")
        return False

def convert_pdb_to_pdbqt_standalone(args):
    """
    Standalone function for PDB to PDBQT conversion that works with multiprocessing.
    
    Parameters
    ----------
    args: tuple
        (pdb_path, pdbqt_path, uniprot_id, pH_value)
        
    Returns
    -------
    dict: Result of the conversion
    """
    pdb_path, pdbqt_path, uniprot_id, pH_value = args
    process_id = os.getpid()
    
    try:
        # Import pybel in the function to avoid issues
        from openbabel import pybel
        
        # Create output directory if it doesn't exist
        os.makedirs(os.path.dirname(pdbqt_path), exist_ok=True)
        
        # Read the PDB file
        molecules = list(pybel.readfile("pdb", str(pdb_path)))
        if not molecules:
            return {
                'success': False,
                'pdb_path': pdb_path,
                'pdbqt_path': pdbqt_path,
                'uniprot_id': uniprot_id,
                'action': 'failed',
                'error': 'No molecules found in PDB file',
                'process_id': process_id
            }
        
        molecule = molecules[0]
        
        # Add partial charges to each atom
        for atom in molecule.atoms:
            atom.OBAtom.GetPartialCharge()
        
        # Write PDBQT file
        molecule.write("pdbqt", str(pdbqt_path), overwrite=True)
        
        return {
            'success': True,
            'pdb_path': pdb_path,
            'pdbqt_path': pdbqt_path,
            'uniprot_id': uniprot_id,
            'action': 'converted',
            'error': None,
            'process_id': process_id
        }
        
    except Exception as e:
        return {
            'success': False,
            'pdb_path': pdb_path,
            'pdbqt_path': pdbqt_path,
            'uniprot_id': uniprot_id,
            'action': 'failed',
            'error': str(e),
            'process_id': process_id
        }

def process_conversion(conversion_task):
    """
    Process a single PDB to PDBQT conversion task.
    This function now wraps the standalone function for compatibility.
    
    Parameters
    ----------
    conversion_task: dict
        Dictionary containing conversion information
        
    Returns
    -------
    dict: Result of the conversion
    """
    pdb_path = conversion_task['pdb_path']
    pdbqt_path = conversion_task['pdbqt_path']
    uniprot_id = conversion_task['uniprot_id']
    is_copy = conversion_task.get('is_copy', False)
    source_pdbqt = conversion_task.get('source_pdbqt', None)
    # Carried in the task rather than read from the module: these run in another
    # process, which must use the pH this run was asked for.
    ph_value = conversion_task.get('ph', PH_VALUE)
    
    if is_copy and source_pdbqt:
        # Handle copying separately since it doesn't need OpenBabel
        try:
            os.makedirs(os.path.dirname(pdbqt_path), exist_ok=True)
            shutil.copy2(source_pdbqt, pdbqt_path)
            return {
                'success': True,
                'pdb_path': pdb_path,
                'pdbqt_path': pdbqt_path,
                'uniprot_id': uniprot_id,
                'action': 'copied',
                'error': None,
                'process_id': os.getpid()
            }
        except Exception as e:
            return {
                'success': False,
                'pdb_path': pdb_path,
                'pdbqt_path': pdbqt_path,
                'uniprot_id': uniprot_id,
                'action': 'failed',
                'error': str(e),
                'process_id': os.getpid()
            }
    else:
        # Use the standalone function for actual conversion
        return convert_pdb_to_pdbqt_standalone((pdb_path, pdbqt_path, uniprot_id, ph_value))

def load_cavity_mapping(mapping_file):
    """Load cavity mapping from CSV file."""
    if not os.path.exists(mapping_file):
        LOG.error(f"Cavity mapping file not found: {mapping_file}")
        LOG.error("Please run extract_cavities.py first.")
        sys.exit(1)
    
    try:
        df = pd.read_csv(mapping_file)
        required_columns = ['UniProt_ID', 'Receptor_PDB', 'Pocket_PDB']
        missing_columns = [col for col in required_columns if col not in df.columns]
        
        if missing_columns:
            LOG.error(f"Required columns missing from cavity mapping: {missing_columns}")
            sys.exit(1)
        
        LOG.info(f"Loaded {len(df)} cavity mappings from {mapping_file}")
        return df
        
    except Exception as e:
        LOG.error(f"Error loading cavity mapping: {e}")
        sys.exit(1)

class MissingInputMapping(RuntimeError):
    """Raised when no acceptable input mapping is available.

    Fatal by design (invariant G8). The old chain fell through
    fixed -> alphafold -> cavity_mapping, and that last step is a 38,709-row
    frame: reaching it converts the entire CavitySpace universe instead of the
    ~980 receptors the campaign used. It logged only an advisory "consider
    running fix_required_pdbs.py first".
    """


def filter_to_required(df, required_csv):
    """Keep only rows whose accession is in an explicit required set."""
    req = pd.read_csv(required_csv)
    cols = {c.lower(): c for c in req.columns}
    acc_col = cols.get('uniprot_id') or cols.get('accession')
    if not acc_col:
        raise MissingInputMapping(
            '%r has no accession column (looked for UniProt_ID / accession); '
            'columns are %s' % (required_csv, list(req.columns)))
    wanted = {str(v).strip() for v in req[acc_col].dropna()}
    before = len(df)
    out = df[df['UniProt_ID'].astype(str).str.strip().isin(wanted)].copy()
    LOG.info('required filter: %d -> %d rows (%d accessions)',
                 before, len(out), len(wanted))
    return out


def load_best_cavity_mapping(explicit=None, allow_cavity_fallback=False):
    """Load the input mapping.

    Args:
        explicit: use exactly this file. Preferred -- it removes the guesswork.
        allow_cavity_fallback: permit falling through to cavity_mapping.csv.
            Off by default: that path converts every CavitySpace receptor.
    """
    if explicit:
        if not os.path.exists(explicit):
            raise MissingInputMapping('input mapping not found: %r' % explicit)
        LOG.info('Using explicit input mapping: %s', explicit)
        return load_cavity_mapping(explicit), explicit

    for path, label in ((FIXED_MAPPING_CSV, 'fixed'), (ALPHAFOLD_MAPPING_CSV, 'AlphaFold')):
        if os.path.exists(path):
            LOG.info('Using %s mapping: %s', label, path)
            return load_cavity_mapping(path), path

    if os.path.exists(CAVITY_MAPPING_CSV) and allow_cavity_fallback:
        LOG.warning('Falling back to %s -- this is the FULL CavitySpace universe '
                        '(38,709 rows in the 2025-06-29 run). Explicitly permitted by '
                        '--allow-cavity-fallback.', CAVITY_MAPPING_CSV)
        return load_cavity_mapping(CAVITY_MAPPING_CSV), CAVITY_MAPPING_CSV

    raise MissingInputMapping(
        'no acceptable input mapping. Run fix_required_pdbs.py or '
        'extract_alphafold_models.py first, or pass --input-mapping. Falling back to '
        '%s would convert every CavitySpace receptor and requires an explicit '
        '--allow-cavity-fallback.' % CAVITY_MAPPING_CSV)

def prepare_conversion_tasks(cavity_df, output_dir, ph=PH_VALUE):
    """
    Prepare conversion tasks with deduplication.
    
    Returns
    -------
    list: List of conversion tasks
    dict: Mapping of UniProt IDs to representative PDBQT files
    """
    LOG.info("Analyzing PDB files for deduplication...")
    
    # Group by UniProt ID and find unique receptor files
    uniprot_groups = cavity_df.groupby('UniProt_ID')
    unique_receptors = {}  # uniprot_id -> (pdb_path, pdb_hash, pdbqt_path)
    conversion_tasks = []
    
    total_files = len(cavity_df)
    processed_files = 0
    
    for uniprot_id, group in tqdm(uniprot_groups, desc="Analyzing receptors"):
        receptor_files = group['Receptor_PDB'].unique()
        
        # Find the representative file (first unique one)
        representative_pdb = None
        representative_hash = None
        representative_pdbqt = None
        
        for pdb_path in receptor_files:
            if not os.path.exists(pdb_path):
                LOG.warning(f"PDB file not found: {pdb_path}")
                continue
            
            # Calculate hash to check if this is a unique structure
            file_hash = get_file_hash(pdb_path)
            
            if representative_pdb is None:
                # This is our representative file
                representative_pdb = pdb_path
                representative_hash = file_hash
                
                # Generate PDBQT path
                pdb_filename = Path(pdb_path).stem
                representative_pdbqt = os.path.join(output_dir, f"{uniprot_id}", f"{pdb_filename}.pdbqt")
                
                # Check if PDBQT already exists
                if os.path.exists(representative_pdbqt):
                    LOG.debug(f"PDBQT already exists for {uniprot_id}: {representative_pdbqt}")
                    # Still track it in unique_receptors for mapping generation
                    unique_receptors[uniprot_id] = (representative_pdb, representative_hash, representative_pdbqt)
                else:
                    # Add conversion task
                    conversion_tasks.append({
                        'pdb_path': representative_pdb,
                        'pdbqt_path': representative_pdbqt,
                        'uniprot_id': uniprot_id,
                        'is_copy': False,
                        'ph': ph
                    })
                    # Track it for mapping generation
                    unique_receptors[uniprot_id] = (representative_pdb, representative_hash, representative_pdbqt)
            
            # For additional files with the same UniProt ID, check if they're identical
            elif file_hash != representative_hash:
                LOG.warning(f"Different receptor structure found for {uniprot_id}: {pdb_path}")
                LOG.warning("This suggests multiple conformations. Converting separately.")
                
                # Generate unique PDBQT path for this variant
                pdb_filename = Path(pdb_path).stem
                variant_pdbqt = os.path.join(output_dir, f"{uniprot_id}", f"{pdb_filename}.pdbqt")
                
                if not os.path.exists(variant_pdbqt):
                    conversion_tasks.append({
                        'pdb_path': pdb_path,
                        'pdbqt_path': variant_pdbqt,
                        'uniprot_id': uniprot_id,
                        'is_copy': False,
                        'ph': ph
                    })
            
            processed_files += 1
    
    LOG.info(f"Found {len(unique_receptors)} unique UniProt IDs")
    LOG.info(f"Prepared {len(conversion_tasks)} conversion tasks")
    
    return conversion_tasks, unique_receptors

def create_updated_mapping(cavity_df, unique_receptors, output_dir):
    """Create updated mapping CSV with PDBQT paths."""
    LOG.info("Creating updated mapping with PDBQT paths...")
    
    updated_rows = []
    for _, row in cavity_df.iterrows():
        uniprot_id = row['UniProt_ID']
        receptor_pdb = row['Receptor_PDB']
        pocket_pdb = row['Pocket_PDB']
        
        # Find corresponding PDBQT file
        if uniprot_id in unique_receptors:
            # Check if this specific PDB file has a PDBQT counterpart
            pdb_filename = Path(receptor_pdb).stem
            potential_pdbqt = os.path.join(output_dir, f"{uniprot_id}", f"{pdb_filename}.pdbqt")
            
            if os.path.exists(potential_pdbqt):
                receptor_pdbqt = potential_pdbqt
            else:
                # Use the representative PDBQT
                _, _, representative_pdbqt = unique_receptors[uniprot_id]
                receptor_pdbqt = representative_pdbqt
        else:
            receptor_pdbqt = None
        
        updated_rows.append({
            'UniProt_ID': uniprot_id,
            'Cavity_Index': row.get('Cavity_Index', 1),
            'Receptor_PDB': receptor_pdb,
            'Receptor_PDBQT': receptor_pdbqt,
            'Pocket_PDB': pocket_pdb
        })
    
    updated_df = pd.DataFrame(updated_rows)
    return updated_df

def runtime_namespace(args, step_name):
    """The namespace :func:`step` gets: its ``out_dir`` is the STEP's own folder.

    ``--out-dir`` on this script names where the PDBQT receptors land -- a contract
    ``run_full_workflow.py`` and ``batch_dock.py`` depend on -- so it cannot double
    as the step's private folder. :func:`artifact_step_dir` supplies the log's home:
    ``<run-dir>/steps/<step>`` when a run directory is known, else ``./<step>`` --
    never the invocation cwd, and never beside the artifacts.
    """
    base = artifact_step_dir(step_name, getattr(args, 'run_dir', None))
    runtime = argparse.Namespace(**vars(args))
    runtime.artifact_out_dir = args.out_dir  # what --out-dir means here
    runtime.out_dir = base
    return runtime


def _describe_out_dir(parser):
    """Correct --out-dir's help text for this stage.

    ``add_runtime_arguments()`` documents ``--out-dir`` as "this step's own
    directory for its log and scratch state", which is true everywhere else in the
    repo. Here the flag is the output destination, a contract
    ``run_full_workflow.py`` and ``batch_dock.py`` depend on, and the step's log
    goes to ``--run-dir``/``--log-file`` instead. argparse offers no public way to
    amend an action after the fact, hence the ``_actions`` walk.
    """
    for action in parser._actions:
        if action.dest == 'out_dir':
            action.help = (
                'output destination: the PDBQT receptors are written here, one '
                'directory per accession, and --out records those paths. '
                'run_full_workflow.py points it at <run-dir>/structures/pdbqt. The '
                'log for this step goes to --run-dir / --log-file, not here (default: %s)' % OUTPUT_PDBQT_DIR)
            return parser
    raise AssertionError('add_runtime_arguments() no longer declares --out-dir')


def build_parser():
    """Build the command-line parser for the PDB->PDBQT conversion stage."""
    parser = argparse.ArgumentParser(
        prog='convert_pdb_to_pdbqt.py',
        description=('Convert receptor PDBs to PDBQT. Prefers an explicit '
                     '--input-mapping; the fallback to the full CavitySpace mapping '
                     'must be asked for by name.'))
    parser.add_argument('--input-mapping', default=None,
                        help='exact mapping to convert (fixed_mapping.csv, alphafold_mapping.csv)')
    parser.add_argument('--required', default=None,
                        help='CSV restricting conversion to these accessions')
    parser.add_argument('--allow-cavity-fallback', action='store_true',
                        help='permit falling back to cavity_mapping.csv (the FULL '
                             'CavitySpace universe, 38,709 rows in the 2025-06-29 run)')
    parser.add_argument('--out', default=OUTPUT_MAPPING_CSV,
                        help='pdbqt_mapping.csv to write (default: %(default)s)')
    parser.add_argument('--threads', type=int, default=NUM_THREADS,
                        help='worker processes; the PDBQT_THREADS environment '
                             'variable supplies the default (default: %(default)s)')
    parser.add_argument('--timeout', type=int, default=CONVERSION_TIMEOUT,
                        help='seconds allowed per conversion before it is abandoned; '
                             'the PDBQT_TIMEOUT environment variable supplies the '
                             'default (default: %(default)s)')
    parser.add_argument('--ph', type=float, default=PH_VALUE,
                        help='protonation pH passed to the OpenBabel conversion. NOTE: '
                             'the CorrectForPH call is currently commented out, so the '
                             'effective receptor protonation is the one '
                             'fix_required_pdbs.py --ph applied (default: %(default)s)')
    parser.add_argument('--run-dir', default=None,
                        help='campaign run directory; when given, this step logs to '
                             '<run-dir>/steps/' + STEP_NAME + '/ instead of beside --out')
    # --out-dir keeps this script's own meaning (where PDBQT files land); the
    # step's private folder is derived by runtime_namespace() instead.
    add_runtime_arguments(parser, STEP_NAME, default_out_dir=OUTPUT_PDBQT_DIR)
    return _describe_out_dir(parser)


def _run(args, log):
    """Do the work and return a process exit code. Logging is already configured."""
    start_time = time.time()
    out_dir = args.out_dir
    out_csv = args.out
    threads = args.threads
    timeout = args.timeout

    log.info("Starting PDB to PDBQT conversion workflow")
    log.info(f"Input mapping: {args.input_mapping or 'auto-select'}")
    log.info(f"Output directory: {out_dir}")
    log.info(f"Output mapping: {out_csv}")
    log.info(f"Number of workers: {threads}")
    log.info(f"Using processes: {USE_PROCESSES}")
    log.info(f"Conversion timeout: {timeout}s")
    log.info(f"pH value: {args.ph}")
    log.info(f"CPU count: {CPU_COUNT}")
    check_system_resources(log)
    log.info("Note: Now using ProcessPoolExecutor for better OpenBabel compatibility")
    
    # Load the input mapping BEFORE creating anything on disk.
    try:
        cavity_df, source_file = load_best_cavity_mapping(
            explicit=args.input_mapping,
            allow_cavity_fallback=args.allow_cavity_fallback,
        )
        if args.required:
            cavity_df = filter_to_required(cavity_df, args.required)
    except MissingInputMapping as exc:
        log.error("%s", exc)
        return 2

    os.makedirs(out_dir, exist_ok=True)
    log.info(f"Loaded {len(cavity_df)} cavity mappings from {source_file}")
    
    # Prepare conversion tasks with deduplication
    conversion_tasks, unique_receptors = prepare_conversion_tasks(
        cavity_df, out_dir, ph=args.ph)
    
    if not conversion_tasks:
        log.info("No conversion tasks needed. All PDBQT files already exist.")
    else:
        # Perform parallel conversion with timeout handling
        log.info(f"Starting parallel conversion of {len(conversion_tasks)} files...")
        
        successful_conversions = 0
        failed_conversions = 0
        timeout_conversions = 0
        
        # Choose executor based on configuration
        executor_class = ProcessPoolExecutor  # Always use ProcessPoolExecutor for better OpenBabel compatibility
        executor_name = "processes"
        
        log.info(f"Using {executor_name} for parallelization")
        
        with executor_class(max_workers=threads) as executor:
            # Submit all tasks
            future_to_task = {executor.submit(process_conversion, task): task for task in conversion_tasks}
            
            # Track unique processes used
            unique_processes = set()
            
            # Process results with progress bar and timeout
            for future in tqdm(as_completed(future_to_task), total=len(conversion_tasks), 
                             desc="Converting PDB to PDBQT"):
                try:
                    # Wait for result with timeout
                    result = future.result(timeout=timeout)
                    
                    # Track process usage
                    if 'process_id' in result:
                        unique_processes.add(result['process_id'])
                    
                    if result['success']:
                        successful_conversions += 1
                        if result['action'] == 'converted':
                            log.debug(f"Converted: {result['pdb_path']} -> {result['pdbqt_path']}")
                        elif result['action'] == 'copied':
                            log.debug(f"Copied: {result['pdbqt_path']}")
                    else:
                        failed_conversions += 1
                        log.error(f"Failed to convert {result['pdb_path']}: {result['error']}")
                        
                except TimeoutError:
                    timeout_conversions += 1
                    task = future_to_task[future]
                    log.error(f"Timeout converting {task['pdb_path']} (>{timeout}s)")
                    future.cancel()
                except Exception as e:
                    failed_conversions += 1
                    task = future_to_task[future]
                    log.error(f"Exception converting {task['pdb_path']}: {e}")
        
        # Log process usage statistics
        log.info(f"Used {len(unique_processes)} unique processes out of {threads} configured")
        if len(unique_processes) == 1:
            log.warning("Only 1 process was used! Parallelization may not be working correctly.")
        else:
            log.info(f"✓ Parallel execution working with {len(unique_processes)} processes")
        
        log.info(f"Conversion completed: {successful_conversions} successful, {failed_conversions} failed, {timeout_conversions} timeout")
    
    # Create updated mapping CSV
    updated_df = create_updated_mapping(cavity_df, unique_receptors, out_dir)
    updated_df.to_csv(out_csv, index=False)
    
    # Summary statistics
    total_pdbqt_files = len([f for f in Path(out_dir).rglob("*.pdbqt")])
    
    elapsed_time = time.time() - start_time
    
    log.info(f"\n--- Conversion Summary ---")
    log.info(f"Total cavity mappings processed: {len(cavity_df)}")
    log.info(f"Unique UniProt IDs: {len(unique_receptors)}")
    log.info(f"PDBQT files created/found: {total_pdbqt_files}")
    log.info(f"Updated mapping saved to: {out_csv}")
    log.info(f"Total processing time: {elapsed_time:.2f} seconds")
    
    # Verify the output
    missing_pdbqt = updated_df[updated_df['Receptor_PDBQT'].isna()]
    if len(missing_pdbqt) > 0:
        log.warning(f"Warning: {len(missing_pdbqt)} entries missing PDBQT files")
    else:
        log.info("All entries have corresponding PDBQT files!")
    return 0


def main(argv=None):
    """Convert the receptors to PDBQT; returns a process exit code."""
    args = build_parser().parse_args(argv)
    with step(STEP_NAME, runtime_namespace(args, STEP_NAME)) as ctx:
        rc = _run(args, ctx.logger)
        if rc:
            # step() only sees a clean return, so an exit code has to be reported
            # (and notified) here or a failed run would be announced as a success.
            ctx.logger.error('%s exited with code %d', STEP_NAME, rc)
            ctx.notify('failure', '%s: FAILED (exit code %d)' % (STEP_NAME, rc),
                       priority=1)
    return rc


if __name__ == "__main__":
    sys.exit(main())
