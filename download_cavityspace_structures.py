#!/usr/bin/env python3
"""Download CavitySpace AlphaFold models for the accessions in a cavity mapping.

SUPERSEDED for normal runs: phase 6b of the pipeline is
``extract_alphafold_models.py --archive``, which pulls the same structures out of
a local AlphaFold tar archive with no network at all. This script is retained for
the case where no local archive exists and the models must come from the
CavitySpace service. It is not part of ``run_full_workflow.py``.

Features:
- Parallel downloading using multiple threads (with respectful delays)
- Resume capability: Skips already downloaded files
- Progress tracking and detailed logging
- Downloads AlphaFold PDB files from CavitySpace
- Integrates with existing cavity mapping workflow
- Rate limiting to be respectful to CavitySpace servers

Prerequisites:
- cavity_mapping.csv (generated by extract_cavities.py)
- Internet connection to the CavitySpace service (--base-url)

Note that --db-version is interpolated into both the request URL and the local
filename, so it must match what the service actually serves.

Usage::

    python3 download_cavityspace_structures.py \
        --cavity-mapping <run-dir>/manifests/cavity_mapping.csv \
        --structures-dir <run-dir>/structures/cavityspace \
        --out <run-dir>/manifests/cavityspace_mapping.csv \
        --run-dir <run-dir>

    # a different host, gentler on it, and a ping if it fails
    python3 download_cavityspace_structures.py --cavity-mapping cavity_mapping.csv \
        --base-url http://example.org/csservice/item --threads 4 --request-delay 2.0 \
        --notify

Output:
    - --structures-dir: downloaded AlphaFold structures, one folder per accession
    - --out: mapping CSV with structure paths and a CavitySpace_Available column
    - <out-dir>/download_cavityspace_structures.log
"""

import argparse
import logging
import os
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

import pandas as pd
import requests
from tqdm import tqdm

from dock_selectivity.runtime import add_runtime_arguments, resolve_out_dir, step

STEP_NAME = "download_cavityspace_structures"

# --- Configuration ------------------------------------------------------------
# Defaults only: every one of these is a flag. Nothing here points at a specific
# campaign; the relative defaults resolve against the invocation directory, which
# is the run directory by convention.
DEFAULT_CAVITY_MAPPING_CSV = "cavity_mapping.csv"   # Input file from extract_cavities.py
DEFAULT_OUTPUT_AF_DIR = "cavityspace_structures"    # Downloaded structures land here
DEFAULT_OUTPUT_MAPPING_CSV = "cavityspace_mapping.csv"
DEFAULT_NUM_THREADS = 8          # Deliberately low: this is someone else's server
DEFAULT_DATABASE_VERSION = "v1"  # CavitySpace serves v1 AlphaFold models
DEFAULT_REQUEST_DELAY = 1.0      # Seconds between requests (be respectful!)
DEFAULT_TIMEOUT = 60.0           # Seconds per HTTP request
DEFAULT_MAX_RETRIES = 3
DEFAULT_BASE_URL = "http://60.205.184.249:8000/csservice/item"

# --- Implementation detail (protocol/schema, not configuration) ---------------
REQUIRED_COLUMNS = ['UniProt_ID', 'Fragment_ID']
MAPPING_COLUMNS = ['UniProt_ID', 'Fragment_ID', 'Cavity_Index', 'Receptor_PDB',
                   'Pocket_PDB', 'AlphaFold_ID', 'CavitySpace_Available']
_HTTP_HEADERS = {
    'User-Agent': 'Consensus-Docking-Workflow/1.0 (Research Project)',
    'Accept': 'application/octet-stream',
}
_CHUNK_BYTES = 8192

LOG = logging.getLogger(STEP_NAME)


def download_file(url, output_path, delay=DEFAULT_REQUEST_DELAY,
                  timeout=DEFAULT_TIMEOUT, max_retries=DEFAULT_MAX_RETRIES):
    """
    Download a file from URL with retry logic and respectful delays.

    Parameters
    ----------
    url: str
        URL to download from
    output_path: str
        Local path to save file
    delay: float
        Base delay in seconds before each request (doubled per retry)
    timeout: float
        Per-request timeout in seconds
    max_retries: int
        Maximum number of retry attempts

    Returns
    -------
    bool: True if download successful, False otherwise
    """
    for attempt in range(max_retries):
        try:
            # Check if file already exists
            if os.path.exists(output_path) and os.path.getsize(output_path) > 0:
                return True

            # Create directory if it doesn't exist
            os.makedirs(os.path.dirname(output_path), exist_ok=True)

            # Add respectful delay before making request
            if attempt > 0:
                time.sleep(delay * (2 ** attempt))  # Exponential backoff
            else:
                time.sleep(delay)  # Base delay

            # Download using requests with streaming
            response = requests.get(url, stream=True, timeout=timeout, headers=_HTTP_HEADERS)
            response.raise_for_status()

            # Write file
            with open(output_path, 'wb') as f:
                for chunk in response.iter_content(chunk_size=_CHUNK_BYTES):
                    f.write(chunk)

            # Verify file was downloaded and has content
            if os.path.exists(output_path) and os.path.getsize(output_path) > 0:
                return True
            else:
                LOG.warning("Downloaded file is empty: %s", output_path)
                return False

        except requests.exceptions.HTTPError as e:
            if e.response is not None and e.response.status_code == 404:
                LOG.warning("Structure not found in CavitySpace for %s", url)
                return False
            LOG.warning("Download attempt %d failed for %s: %s", attempt + 1, url, e)
        except Exception as e:
            LOG.warning("Download attempt %d failed for %s: %s", attempt + 1, url, e)

        if attempt < max_retries - 1:
            wait_time = delay * (2 ** attempt)
            LOG.info("Waiting %.1fs before retry...", wait_time)
            time.sleep(wait_time)

    return False


def process_download_task(download_task):
    """
    Process a single CavitySpace download task.

    Parameters
    ----------
    download_task: dict
        Dictionary containing download information, including the per-request
        delay, timeout and retry budget resolved from the command line.

    Returns
    -------
    dict: Result of the download
    """
    uniprot_id = download_task['uniprot_id']
    fragment_id = download_task['fragment_id']
    model_url = download_task['model_url']
    model_path = download_task['model_path']

    try:
        # Download model PDB file
        model_success = download_file(model_url, model_path,
                                      delay=download_task['delay'],
                                      timeout=download_task['timeout'],
                                      max_retries=download_task['max_retries'])

        return {
            'success': model_success,
            'uniprot_id': uniprot_id,
            'fragment_id': fragment_id,
            'model_path': model_path if model_success else None,
            'model_downloaded': model_success,
            'error': None if model_success else 'Download failed or structure not available'
        }

    except Exception as e:
        return {
            'success': False,
            'uniprot_id': uniprot_id,
            'fragment_id': fragment_id,
            'model_path': None,
            'model_downloaded': False,
            'error': str(e)
        }


class MissingCavityMapping(Exception):
    """The cavity mapping this stage downloads for is absent or unusable."""


def load_cavity_mapping(mapping_file):
    """Load cavity mapping from CSV file, or raise MissingCavityMapping."""
    if not os.path.exists(mapping_file):
        raise MissingCavityMapping(
            "cavity mapping file not found: {0}. Run extract_cavities.py first, "
            "or point --cavity-mapping at the mapping it wrote.".format(mapping_file))

    try:
        df = pd.read_csv(mapping_file)
    except Exception as exc:
        raise MissingCavityMapping(
            "could not read cavity mapping {0}: {1}".format(mapping_file, exc))

    missing_columns = [col for col in REQUIRED_COLUMNS if col not in df.columns]
    if missing_columns:
        raise MissingCavityMapping(
            "required columns missing from cavity mapping {0}: {1}".format(
                mapping_file, missing_columns))

    LOG.info("Loaded %d cavity mappings from %s", len(df), mapping_file)
    return df


def model_paths(uniprot_id, fragment_id, output_dir, db_version, base_url):
    """Return (alphafold_id, model_url, model_path) for one accession/fragment."""
    alphafold_id = "AF-{0}-F{1}".format(uniprot_id, fragment_id)
    stem = "{0}-model_{1}".format(alphafold_id, db_version)
    # {base}/{accession}/structure/alphafold/{stem}/{stem}.pdb
    model_url = "{0}/{1}/structure/alphafold/{2}/{2}.pdb".format(
        base_url.rstrip('/'), uniprot_id, stem)
    model_path = os.path.join(output_dir, str(uniprot_id), "F{0}".format(fragment_id),
                              "{0}.pdb".format(stem))
    return alphafold_id, model_url, model_path


def prepare_download_tasks(cavity_df, output_dir, db_version, base_url,
                           delay, timeout, max_retries):
    """
    Prepare CavitySpace download tasks.

    Returns
    -------
    list: List of download tasks
    dict: Statistics about downloads to be performed
    """
    LOG.info("Preparing CavitySpace download tasks...")

    # Get unique UniProt ID and Fragment ID combinations
    unique_combinations = cavity_df[REQUIRED_COLUMNS].drop_duplicates()
    download_tasks = []

    for _, row in tqdm(unique_combinations.iterrows(), total=len(unique_combinations),
                       desc="Preparing download tasks"):
        uniprot_id = row['UniProt_ID']
        fragment_id = row['Fragment_ID']

        alphafold_id, model_url, model_path = model_paths(
            uniprot_id, fragment_id, output_dir, db_version, base_url)

        # Check if file already exists
        model_exists = os.path.exists(model_path) and os.path.getsize(model_path) > 0

        if model_exists:
            LOG.debug("CavitySpace structure already exists for %s F%s", uniprot_id, fragment_id)
            continue

        download_tasks.append({
            'uniprot_id': uniprot_id,
            'fragment_id': fragment_id,
            'alphafold_id': alphafold_id,
            'model_url': model_url,
            'model_path': model_path,
            'delay': delay,
            'timeout': timeout,
            'max_retries': max_retries,
        })

    stats = {
        'total_combinations': len(unique_combinations),
        'unique_uniprot_ids': len(cavity_df['UniProt_ID'].unique()),
        'download_tasks': len(download_tasks),
        'already_downloaded': len(unique_combinations) - len(download_tasks)
    }

    LOG.info("Found %d unique UniProt IDs with %d fragments",
             stats['unique_uniprot_ids'], stats['total_combinations'])
    LOG.info("Prepared %d download tasks", stats['download_tasks'])
    LOG.info("Already downloaded: %d structures", stats['already_downloaded'])

    return download_tasks, stats


def create_cavityspace_mapping(cavity_df, output_dir, db_version, base_url):
    """Create mapping DataFrame with CavitySpace structure paths."""
    LOG.info("Creating CavitySpace mapping...")

    updated_rows = []
    for _, row in cavity_df.iterrows():
        uniprot_id = row['UniProt_ID']
        fragment_id = row['Fragment_ID']
        pocket_pdb = row['Pocket_PDB']

        alphafold_id, _url, structure_path = model_paths(
            uniprot_id, fragment_id, output_dir, db_version, base_url)

        # Check if structure file exists
        structure_exists = os.path.exists(structure_path) and os.path.getsize(structure_path) > 0

        updated_rows.append({
            'UniProt_ID': uniprot_id,
            'Fragment_ID': fragment_id,
            'Cavity_Index': row.get('Cavity_Index', 1),
            'Receptor_PDB': structure_path if structure_exists else None,
            'Pocket_PDB': pocket_pdb,
            'AlphaFold_ID': alphafold_id,
            'CavitySpace_Available': structure_exists
        })

    # An empty frame still needs its columns: the caller sums CavitySpace_Available.
    return pd.DataFrame(updated_rows, columns=MAPPING_COLUMNS)


def build_parser():
    """Build the command-line parser for the CavitySpace download stage."""
    parser = argparse.ArgumentParser(
        prog="download_cavityspace_structures.py",
        description=("Download CavitySpace AlphaFold models for the accessions in a "
                     "cavity mapping. Superseded by extract_alphafold_models.py, which "
                     "reads a local archive instead of the network."))
    parser.add_argument('--cavity-mapping', default=DEFAULT_CAVITY_MAPPING_CSV,
                        help='cavity mapping CSV from extract_cavities.py, naming the '
                             'accessions and fragments to fetch (default: %(default)s)')
    parser.add_argument('--structures-dir', default=DEFAULT_OUTPUT_AF_DIR,
                        help='directory the downloaded structures are written to '
                             '(default: %(default)s)')
    parser.add_argument('--out', default=DEFAULT_OUTPUT_MAPPING_CSV,
                        help='mapping CSV to write, with the structure paths and a '
                             'CavitySpace_Available column (default: %(default)s)')
    parser.add_argument('--threads', type=int, default=DEFAULT_NUM_THREADS,
                        help='concurrent downloads; keep it low, this is someone '
                             'else\'s server (default: %(default)s)')
    parser.add_argument('--db-version', default=DEFAULT_DATABASE_VERSION,
                        help='AlphaFold database version CavitySpace serves; it is '
                             'interpolated into both the URL and the local filename, so '
                             'it must match the service (default: %(default)s)')
    parser.add_argument('--request-delay', type=float, default=DEFAULT_REQUEST_DELAY,
                        help='seconds to wait before each request, doubled per retry '
                             '(default: %(default)s)')
    parser.add_argument('--timeout', type=float, default=DEFAULT_TIMEOUT,
                        help='per-request timeout in seconds (default: %(default)s)')
    parser.add_argument('--max-retries', type=int, default=DEFAULT_MAX_RETRIES,
                        help='download attempts per structure before giving up '
                             '(default: %(default)s)')
    parser.add_argument('--base-url', default=DEFAULT_BASE_URL,
                        help='CavitySpace item service base URL; override it when the '
                             'service moves (default: %(default)s)')
    parser.add_argument('--run-dir', default=None,
                        help='campaign run directory; when given, this step logs to '
                             '<run-dir>/steps/' + STEP_NAME + '/ (default: ./' + STEP_NAME + ')')
    return add_runtime_arguments(parser, STEP_NAME)


def main(argv=None):
    """Download the CavitySpace models; returns a process exit code."""
    args = build_parser().parse_args(argv)
    resolve_out_dir(args, STEP_NAME, args.run_dir)

    try:
        with step(STEP_NAME, args) as ctx:
            log = ctx.logger
            start_time = time.time()

            log.info("Starting CavitySpace AlphaFold model download workflow")
            log.info("Input: %s", args.cavity_mapping)
            log.info("Structures directory: %s", args.structures_dir)
            log.info("Output mapping: %s", args.out)
            log.info("Base URL: %s (database version %s)", args.base_url, args.db_version)
            log.info("Threads: %d, request delay: %.1fs, timeout: %.0fs, retries: %d",
                     args.threads, args.request_delay, args.timeout, args.max_retries)

            try:
                cavity_df = load_cavity_mapping(args.cavity_mapping)
            except MissingCavityMapping as exc:
                log.error("%s", exc)
                raise SystemExit(2)

            os.makedirs(args.structures_dir, exist_ok=True)

            download_tasks, stats = prepare_download_tasks(
                cavity_df, args.structures_dir, args.db_version, args.base_url,
                args.request_delay, args.timeout, args.max_retries)

            if not download_tasks:
                log.info("No download tasks needed. All CavitySpace structures already downloaded.")
            else:
                log.info("Starting parallel download of %d CavitySpace structures...",
                         len(download_tasks))

                successful_downloads = 0
                failed_downloads = 0

                with ThreadPoolExecutor(max_workers=args.threads) as executor:
                    future_to_task = {executor.submit(process_download_task, task): task
                                      for task in download_tasks}

                    for future in tqdm(as_completed(future_to_task), total=len(download_tasks),
                                       desc="Downloading CavitySpace structures"):
                        result = future.result()

                        if result['success']:
                            successful_downloads += 1
                            log.debug("Downloaded: %s F%s",
                                      result['uniprot_id'], result['fragment_id'])
                        else:
                            failed_downloads += 1
                            log.warning("Failed to download %s F%s: %s",
                                        result['uniprot_id'], result['fragment_id'],
                                        result['error'])

                log.info("Download completed: %d successful, %d failed",
                         successful_downloads, failed_downloads)

            cavityspace_df = create_cavityspace_mapping(
                cavity_df, args.structures_dir, args.db_version, args.base_url)
            out_parent = os.path.dirname(os.path.abspath(args.out))
            if out_parent:
                os.makedirs(out_parent, exist_ok=True)
            cavityspace_df.to_csv(args.out, index=False)

            total_structure_files = len(list(Path(args.structures_dir).rglob("*.pdb")))
            available_structures = int(cavityspace_df['CavitySpace_Available'].sum())
            elapsed_time = time.time() - start_time

            log.info("--- Download Summary ---")
            log.info("Total cavity mappings processed: %d", len(cavity_df))
            log.info("Unique UniProt IDs: %d", stats['unique_uniprot_ids'])
            log.info("Total fragments: %d", stats['total_combinations'])
            log.info("CavitySpace PDB files downloaded/found: %d", total_structure_files)
            log.info("Available structures: %d", available_structures)
            log.info("Updated mapping saved to: %s", args.out)
            log.info("Total processing time: %.2f seconds", elapsed_time)

            missing_structures = len(cavityspace_df) - available_structures
            if missing_structures > 0:
                log.warning("%d entries are missing CavitySpace structures; those UniProt "
                            "IDs may not exist in the database", missing_structures)
            else:
                log.info("All entries have corresponding CavitySpace structures!")
    except SystemExit as exc:
        return int(exc.code or 0)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
